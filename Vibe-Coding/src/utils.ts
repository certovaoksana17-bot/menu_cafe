// ── Форматирование цены ───────────────────────
// Превращает 1299 → "1 299", 299 → "299"
// Нужно чтобы большие суммы читались без труда
export function formatPrice(amount: number): string {
  return amount.toLocaleString("ru-RU");
}

// ── Валидация адреса доставки ─────────────────
// Возвращает строку с ошибкой или null если всё корректно.
// Правила проверяются по порядку — первая сработавшая возвращается.
export function validateAddress(value: string): string | null {
  const trimmed = value.trim();

  if (trimmed.length === 0) {
    return "Введите адрес доставки";
  }
  if (trimmed.length < 10) {
    return "Адрес слишком короткий — укажите улицу и дом";
  }
  // В адресе должна быть хотя бы одна цифра (номер дома)
  if (!/\d/.test(trimmed)) {
    return "Укажите номер дома";
  }
  // В адресе должны быть буквы (название улицы)
  if (!/[а-яёa-z]/i.test(trimmed)) {
    return "Укажите название улицы";
  }
  return null; // всё корректно
}
